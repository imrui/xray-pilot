package service

import (
	"fmt"
	"github.com/imrui/xray-pilot/internal/entity"
	"github.com/imrui/xray-pilot/internal/repository"
	"github.com/imrui/xray-pilot/internal/xray"
	xssh "github.com/imrui/xray-pilot/pkg/ssh"
	"time"
)

func ReconcileDeployment(id uint) (*entity.ConfigDeployment, error) {
	var job entity.ConfigDeployment
	if err := repository.DB.First(&job, id).Error; err != nil {
		return nil, err
	}
	if job.Status != "unknown" {
		return &job, nil
	}
	defer lockNode(job.NodeID)()
	state, release, err := repository.AcquireConfigLease(job.NodeID)
	if err != nil {
		return nil, err
	}
	defer release()
	svc := NewSyncService()
	n, err := svc.nodeRepo.FindByID(job.NodeID)
	if err != nil {
		return nil, err
	}
	p := svc.sshParams(n)
	c, err := xssh.Connect(xssh.Config{Host: p.Host, Port: p.Port, User: p.User, KeyPath: p.KeyPath, KnownHostsPath: p.KnownHostsPath})
	if err != nil {
		return nil, fmt.Errorf("节点不可达，运行状态仍未确认")
	}
	defer c.Close()
	raw, err := c.ReadRemoteFile(p.ConfigPath)
	if err != nil {
		return nil, fmt.Errorf("无法读取节点配置")
	}
	actual := xray.ConfigHash(raw)
	if actual != job.DesiredHash {
		return nil, fmt.Errorf("节点文件不是本任务版本，请核对漂移后处理")
	}
	// This content was generated by the recorded job; adopt only its disk receipt.
	if err := repository.DB.Model(&entity.NodeConfigState{}).Where("node_id = ? AND lease_owner = ?", job.NodeID, state.LeaseOwner).Updates(map[string]any{"disk_hash": actual, "disk_revision": job.DesiredRevision}).Error; err != nil {
		return nil, err
	}
	process, verifyErr := c.VerifyConfigReceipt(raw, p.ConfigPath)
	if verifyErr != nil {
		process, verifyErr = c.VerifyRunningConfig(raw, p.ConfigPath, p.ProbeURL)
	}
	if verifyErr != nil {
		job.Error = "磁盘已确认，运行态未确认；可用最新配置重试"
	} else {
		latest, _, buildErr := svc.buildConfig(n)
		if buildErr == nil && xray.ConfigHash(latest) == actual {
			snapshot, err := NewRoutingService().Effective(n.ID)
			if err != nil {
				return nil, err
			}
			if err := rememberDesired(state, actual); err != nil {
				return nil, err
			}
			if err := svc.recordApplied(state, raw, process, snapshot); err != nil {
				return nil, err
			}
			if err := finishNodeStatus(state, actual, true); err != nil {
				return nil, err
			}
			job.Status = "succeeded"
			job.Error = ""
		} else {
			job.Status = "superseded"
			job.Error = "旧版本曾成功应用，当前期望已变化"
			if err := leaseUpdate(repository.DB, state, map[string]any{"runtime_hash": actual, "runtime_authorization_hash": xssh.AuthorizationHash(raw), "process_id": process, "verified_at": time.Now(), "recovery_pending": true}); err != nil {
				return nil, err
			}
		}
	}
	if err := repository.DB.Model(&entity.ConfigDeployment{}).Where("id = ? AND status = ?", id, "unknown").Updates(map[string]any{"status": job.Status, "error": job.Error}).Error; err != nil {
		return nil, err
	}
	return &job, nil
}
